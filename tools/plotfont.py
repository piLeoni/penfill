"""A single-stroke vector font, so labels plot as lines instead of text.

A pen plotter cannot draw a font: it needs polylines. This is a compact
Hershey-style font — every glyph is a list of strokes in a 0..1 box, so a
label comes out as `penfill` strokes and can go into the SVG as ordinary
paths.

Coordinates are `(x, y)` with y up, x in 0..advance and y in 0..1 (baseline at
0, cap height at 1). Lowercase letters use the same box; descenders dip below
0. The set covers what a label needs: letters, digits, and punctuation.
"""

from __future__ import annotations

# Each glyph: a list of polylines. x left→right, y bottom→top.
# A single point (a dot) is written as a one-point polyline and drawn as a
