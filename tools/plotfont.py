# Glyphs are spaced proportionally: each one takes its own ink width plus
# GAP, so an `i` or a `.` does not leave a hole in the word. Both are in ems
# of the cap height.
GAP = 0.28
SPACE_ADVANCE = 0.55


def _glyph(ch: str):
    g = GLYPHS.get(ch)
    if g is None:
        g = GLYPHS.get(ch.upper(), GLYPHS.get("?"))
    return g


def _extent(glyph) -> tuple[float, float]:
    xs = [px for stroke in glyph for (px, _) in stroke]
    return min(xs), max(xs)


def _layout(text: str, size: float, letter_spacing: float):
    """(x offset of each glyph's left ink edge, glyph or None) and total width."""
    placed = []
    cx = 0.0
    for i, ch in enumerate(text):
        if ch == " ":
            cx += size * SPACE_ADVANCE + letter_spacing
            continue
        glyph = _glyph(ch)
        if glyph is None:
            cx += size * SPACE_ADVANCE + letter_spacing
            continue
        lo, hi = _extent(glyph)
        placed.append((cx - lo * size, glyph))
        cx += (hi - lo) * size
        if i < len(text) - 1:
            cx += size * GAP + letter_spacing
    return placed, cx


def text_strokes(
    text: str,
    x: float,
    baseline_y: float,
    size: float,
    *,
    letter_spacing: float = 0.0,
    align: str = "left",
) -> list[list[tuple[float, float]]]:
    """A string as strokes, in the page's coordinates.

    `size` is the cap height in mm. `baseline_y` is the line the letters sit
    on. `align` is `"left"`, `"center"` or `"right"`: where `x` falls.
    """
    if not text:
        return []
    placed, total = _layout(text, size, letter_spacing)
    if align == "center":
        start = x - total / 2.0
    elif align == "right":
        start = x - total
    else:
        start = x

    out: list[list[tuple[float, float]]] = []
    for ox, glyph in placed:
        for stroke in glyph:
            # glyphs are y-up; the page is y-down
            pts = [(start + ox + px * size, baseline_y - py * size) for (px, py) in stroke]
            if len(pts) == 1:
                # A dot: a tiny horizontal tick, so it is a real stroke.
                px, py = pts[0]
                pts = [(px, py), (px + size * 0.04, py)]
            out.append(pts)
    return out


def text_width(text: str, size: float, *, letter_spacing: float = 0.0) -> float:
    """How wide `text_strokes` would draw `text` at cap height `size`, in mm."""
    return _layout(text, size, letter_spacing)[1]
